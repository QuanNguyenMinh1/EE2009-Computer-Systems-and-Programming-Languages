.ORIG X3010

LD R3, ASCII_OFFSET
LD R6, ADDR_ARR
ADD R1, R1, #15
ADD R1, R1, #2

FILL:	ADD R2, R2, #1
	STR R2, R6, #0

	ADD R6, R6, #1
	ADD R1, R1, #-1
	BRp FILL
	AND R1, R1, #0
	ADD R1, R1, #15
	ADD R1, R1, #2
	LD R6, ADDR_ARR
	AND R4, R4, #0

LOOP:	LDR R0, R6, #0

DEMSO_CHAN_LE:
	AND R0, R0, #1
	ADD R0, R0, #-1
	BRz LA_LE
	BRn LA_CHAN

NEXT:	ADD R6, R6, #1
	ADD R1, R1, #-1
	BRp LOOP

KTHUC:	ADD R0, R4, R3
	OUT
	ADD R0, R5, R3
	OUT

HALT

LA_CHAN:
	ADD R4, R4, #1
	BRnzp NEXT
LA_LE:
	ADD R5, R5, #1
	BRnzp NEXT

ASCII_OFFSET	.FILL X30
ADDR_ARR	.FILL X3100
ADDR_DES	.FILL X3115
.END