.ORIG X3000
IN
AND R1, R1, #0
ADD R1, R1, #1
LD R3, ASCII_OFFSET
ADD R4, R3, #0
NOT R4, R4
ADD R4, R4, #1
ADD R0, R0, R4

AND R2, R1, R0

NOT R1, R1
ADD R1, R1, #1

ADD R2, R2, R1
BRn LA_SO_CHAN
BRz LA_SO_LE

LA_SO_CHAN:
AND R0, R0, #0

ADD R0, R0, R3
OUT
BRnzp SKIP

LA_SO_LE:
AND R0, R0, #0
ADD R0, R0, #1
ADD R0, R0, R3
OUT
BRnzp SKIP

SKIP:
HALT
ASCII_OFFSET	.FILL X30
.END