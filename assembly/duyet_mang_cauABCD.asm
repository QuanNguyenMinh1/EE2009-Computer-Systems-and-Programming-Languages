	AND R0, R0, #0
	ADD R0, R0, #0

	LD R1, ADDR_ARR
	AND R2, R2, #0	; DATA_FILL_ARR
	AND R4, R4, #0	; SUM
	ADD R3, R2, #15	; COUNTER
	ADD R3, R3, #2

FILL_ARR:
	ADD R2, R2, #1
	STR R2, R1, #0
	
	ADD R1, R1, #1
	ADD R3, R3, #-1
	BRp FILL_ARR

	LD R1, ADDR_ARR
	AND R2, R2, #0	; DATA_FILL_ARR
	AND R4, R4, #0	; SUM
	ADD R3, R2, #15	; COUNTER
	ADD R3, R3, #2

DUYET_TINH_SUM:
	LDR R0, R1, #0	
	ADD R4, R4, R0; R4 += R0

	ADD R1, R1, #1
	ADD R3, R3, #-1
	BRp DUYET_TINH_SUM

LUU_SUM:
	LD R1, ADDR_SUM
	STR R4, R1, #0
;; cau B - Dem so am, duong
RESET_B:
	LD R1, ADDR_ARR
	AND R2, R2, #0	; so AM
	AND R4, R4, #0	; so DUONG
	ADD R3, R2, #15	; COUNTER DUYET MANG
	ADD R3, R3, #2
	ADD R6, R4, #0	; COUNTER SHIFT 8	

DUYET_DEM_AM_DUONG:
	LDR R0, R1, #0
	ADD R6, R6, #8
	;DICH 8 BIT
SHIFT_8:
	ADD R0, R0, R0
	ADD R6, R6, #-1
	BRp SHIFT_8
XET_AM_DUONG:
	ADD R0, R0, #0
	BRp LA_DUONG
	BRn LA_AM
NEXT_B:
	ADD R1, R1, #1
	ADD R3, R3, #-1
	BRp DUYET_DEM_AM_DUONG
XUAT_AM_DUONG:
	AND R6, R6, #0
	ADD R6, R6, #-9
	ADD R0, R2, R6	; R2 - R6
	BRnz AM_1_SO
	BRp AM_2_SO
SKIP_B:
	ADD R0, R4, R6	; R2 - R6
	BRnz DUONG_1_SO
	BRp DUONG_2_SO
;; cau C - nhap so k
RESET_C:
	LD R1, ADDR_ARR
	AND R2, R2, #0	; so chan
	AND R4, R4, #0	; so le
	ADD R3, R2, #15	; COUNTER
	ADD R3, R3, #2
	AND R5, R5, #0

	LD R6, ASCII_OFFSET
	NOT R6, R6
	ADD R6, R6, #1

	IN
	ADD R2, R0, R6
	NOT R2, R2
	ADD R2, R2, #1
	AND R6, R6, #0

DUYET_TIM_K:
	LDR R0, R1, #0
	ADD R0, R0, R2	; R0 <- R0 - R2
	BRz BANG_K

SKIP_C:
	ADD R1, R1, #1
	ADD R3, R3, #-1
	BRp DUYET_TIM_K

XUAT_C:	
	ADD R0, R4, #-9
	BRp K_2_CHU
	BRnz K_1_CHU

;; cau D - dem so chan, so le
RESET_D:
	LD R1, ADDR_ARR
	AND R2, R2, #0	; so chan
	AND R4, R4, #0	; so le
	ADD R3, R2, #15	; COUNTER
	ADD R3, R3, #2
	AND R6, R6, #0

DUYET_CHAN_LE:
	LDR R0, R1, #0
	AND R0, R0, #1
	ADD R0, R0, #-1
	BRz LA_SO_LE
	BRn LA_SO_CHAN

SKIP:
	ADD R1, R1, #1
	ADD R3, R3, #-1
	BRp DUYET_CHAN_LE
	
XUAT_CHAN_LE:
	LD R6, ASCII_OFFSET
	ADD R0, R2, R6; CHAN
	OUT
	ADD R0, R4, R6; LE
	OUT

HALT

LA_SO_LE:
	ADD R2, R2, #1
	BRnzp SKIP
LA_SO_CHAN:
	ADD R4, R4, #1
	BRnzp SKIP
LA_AM:
	ADD R2, R2, #1
	BRnzp NEXT_B
LA_DUONG:
	ADD R4, R4, #1
	BRnzp NEXT_B
AM_1_SO:
	LD R3, ASCII_OFFSET
	ADD R0, R2, R3
	OUT
	BRnzp SKIP_B
AM_2_SO:
	AND R3, R3, #0
	ADD R0, R3, #1
	LD R3, ASCII_OFFSET
	ADD R0, R0, R3
	OUT		;HANG CHUC
	AND R3, R3, #0
	ADD R3, R3, #-10
	ADD R0, R2, R3
	LD R3, ASCII_OFFSET
	ADD R0, R0, R3
	OUT		;HANG DON VI
	BRnzp SKIP_B
DUONG_1_SO:
	LD R3, ASCII_OFFSET
	ADD R0, R4, R3
	OUT
	BRnzp RESET_C
DUONG_2_SO:
	AND R3, R3, #0
	ADD R0, R3, #1
	LD R3, ASCII_OFFSET
	ADD R0, R0, R3
	OUT		;HANG CHUC
	AND R3, R3, #0
	ADD R3, R3, #-10
	ADD R0, R4, R3
	LD R3, ASCII_OFFSET
	ADD R0, R0, R3
	OUT		;HANG DON VI
	BRnzp RESET_C
BANG_K:
	ADD R4, R4, #1
	BRnzp SKIP_C
K_1_CHU:
	LD R6, ASCII_OFFSET
	ADD R0, R4, R6
	OUT
	BRnzp RESET_D
K_2_CHU:
	AND R6, R6, #0
	ADD R0, R6, #1
	LD R6, ASCII_OFFSET
	ADD R0, R0, R6
	OUT		;HANG CHUC
	AND R6, R6, #0
	ADD R6, R6, #-10
	ADD R0, R4, R6
	LD R6, ASCII_OFFSET
	ADD R0, R0, R6
	OUT		;HANG DON VI
	BRnzp RESET_D
ADDR_ARR	.FILL X3100
ADDR_SUM	.FILL X3115
ASCII_OFFSET	.FILL X30
