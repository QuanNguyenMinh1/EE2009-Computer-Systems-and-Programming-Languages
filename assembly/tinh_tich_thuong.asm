.ORIG X3000
LD R4, ASCII_OFFSET
NOT R4, R4
ADD R4, R4, #1
AND R2, R2, #0

IN
ADD R1, R0, R4
IN
ADD R2, R0, R4

ADD R3, R2, #0; COUNTER
AND R5, R5, #0; SUM

TINH_TICH:
	ADD R5, R5, R1
	
	ADD R3, R3, #-1
	BRp TINH_TICH
PRE_TINH_THUONG:
	AND R3, R3, #0
	ADD R6, R1, #0
	NOT R4, R2
	ADD R4, R4, #1
TINH_THUONG:
	ADD R3, R3, #1
	ADD R6, R6, R4
	BRp TINH_THUONG

NEXT:	LD R4, ASCII_OFFSET
	ADD R0, R5, R4; OUT TICH
	OUT
	ADD R0, R3, R4; OUT THUONG
	OUT

HALT

ASCII_OFFSET	.FILL X30
.END
